// Compact offline chart data from d3-celestial (BSD-3-Clause): the
// constellations and the Milky Way (the stars come from tools/stars.mjs).
// Download constellations.lines.json, constellations.json,
// constellations.bounds.json, mw.json and LICENSE from
// https://github.com/ofrohn/d3-celestial into a directory, then:
// node tools/coelum.mjs <directory>
import fs from 'node:fs';
import path from 'node:path';
const dir = process.argv[2];
if (!dir) throw new Error('usage: node tools/coelum.mjs <directory>');
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).features;

const names = new Map(read('constellations.json').map((c) => [c.id, c]));
const lines = read('constellations.lines.json').map((c) => {
  const n = names.get(c.id);
  return [n.properties.la, ...n.geometry.coordinates, c.geometry.coordinates];
});

// Boundaries: each edge once, as flat [ra, dec, ra, dec…] polylines.
const round = (x) => Math.round(x * 100) / 100;
const edges = new Map();
for (const f of read('constellations.bounds.json')) for (const ring of f.geometry.coordinates) {
  for (let i = 0; i + 1 < ring.length; i++) {
    const a = ring[i].map(round), b = ring[i + 1].map(round), key = [a, b].map(String).sort().join('|');
    if (!edges.has(key)) edges.set(key, [...a, ...b]);
  }
}
// Join consecutive edges into polylines.
const bounds = [];
for (const e of edges.values()) {
  const last = bounds.at(-1);
  if (last && last.at(-2) === e[0] && last.at(-1) === e[1]) last.push(e[2], e[3]);
  else bounds.push([...e]);
}

// Milky Way isophotes (5 levels), thinned to points 0.6° apart; rings of
// less than four points are dropped.
const milkyWay = read('mw.json').map((f) => f.geometry.coordinates.flatMap((poly) => poly.map((ring) => {
  const out = [];
  let last = null;
  for (const [ra, dec] of ring) {
    if (last && Math.hypot(((ra - last[0] + 540) % 360 - 180) * Math.cos(dec * Math.PI / 180), dec - last[1]) < 0.6) continue;
    out.push(Math.round(ra * 10) / 10, Math.round(dec * 10) / 10); last = [ra, dec];
  }
  return out;
}).filter((r) => r.length >= 8)));

const license = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8');
const json = (x) => JSON.stringify(x);
fs.writeFileSync(new URL('../js/skydata.js', import.meta.url),
  '// Generated by tools/coelum.mjs. Constellation figures, boundaries, label\n' +
  '// positions and Milky Way outlines: Olaf Frohn.\n' +
  '// https://github.com/ofrohn/d3-celestial — see SKY_DATA_LICENSE below.\n' +
  '// CONSTELLATIONS: [Latin name, RA, Dec, arrays of polylines (J2000)].\n' +
  '// BOUNDARIES: flat [RA, Dec, RA, Dec…] polylines (J2000).\n' +
  '// MILKY_WAY: five isophote levels, each a list of flat [RA, Dec…] rings.\n' +
  `export const SKY_DATA_LICENSE = ${json(license)};\n` +
  `export const CONSTELLATIONS = ${json(lines)};\n` +
  `export const BOUNDARIES = ${json(bounds)};\n` +
  `export const MILKY_WAY = ${json(milkyWay)};\n`);
console.log(`${bounds.length} boundary lines, Milky Way ${milkyWay.map((l) => l.reduce((n, r) => n + r.length / 2, 0)).join('/')} points`);
