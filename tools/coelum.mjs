// Compact offline chart data from d3-celestial (BSD-3-Clause) and the
// Hipparcos catalogue (ESA 1997). Download stars.6.json,
// constellations.lines.json, constellations.json, constellations.bounds.json,
// mw.json and LICENSE from https://github.com/ofrohn/d3-celestial into a
// directory, and the Hipparcos flags as hip_main.tsv:
// https://vizier.cfa.harvard.edu/viz-bin/asu-tsv?-source=I/239/hip_main&-out=HIP&-out=Vmag&-out=CCDM&-out=MultFlag&-out=VarFlag&-out=rho&-out=dHp&-out=Hpmax&-out=HPmin&-out=Period&-out=HvarType&Vmag=%3C6.6&-out.max=unlimited
// then: node tools/coelum.mjs <directory>
import fs from 'node:fs';
import path from 'node:path';
const dir = process.argv[2];
if (!dir) throw new Error('usage: node tools/coelum.mjs <directory>');
const read = (f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).features;

// Hipparcos: a double is a CCDM system resolved by Hipparcos at 1.5″ or
// more with a companion within 4 mag, or two chart stars of one CCDM system
// (Albireo, ε Lyrae); a variable varies by more than 0.6 mag (VarFlag 3),
// or by 0.25 mag or more over the Hp range of VarFlag 2 (Betelgeuse).
const hip = new Map();
for (const line of fs.readFileSync(path.join(dir, 'hip_main.tsv'), 'utf8').split('\n')) {
  const f = line.split('\t');
  if (!/^\s*\d+$/.test(f[0] || '')) continue;
  hip.set(Number(f[0]), { ccdm: f[2].trim(), rho: Number(f[5]) || 0, dHp: f[6].trim() === '' ? 99 : Number(f[6]), range: Number(f[8]) - Number(f[7]), varFlag: Number(f[4]) || 0 });
}
const stars = read('stars.6.json').map((s) => [s.id, ...s.geometry.coordinates, s.properties.mag, Number(s.properties.bv) || 0]);
const systems = new Map();
for (const s of stars) { const h = hip.get(s[0]); if (h?.ccdm) systems.set(h.ccdm, (systems.get(h.ccdm) || 0) + 1); }
for (const s of stars) {
  const h = hip.get(s[0]);
  if (!h) continue;
  const flags = (h.ccdm && (h.rho >= 1.5 && h.dHp <= 4 || systems.get(h.ccdm) > 1) ? 1 : 0) | (h.varFlag === 3 || h.varFlag === 2 && h.range >= 0.25 ? 2 : 0);
  if (flags) s.push(flags);
}

const names = new Map(read('constellations.json').map((c) => [c.id, c]));
const lines = read('constellations.lines.json').map((c) => {
  const n = names.get(c.id);
  return [n.properties.la, ...n.geometry.coordinates, c.geometry.coordinates];
});

// Boundaries: each edge once, as flat [ra, dec, ra, dec…] polylines.
const round = (x) => Math.round(x * 100) / 100;
const edges = new Map();
for (const f of read('constellations.bounds.json')) for (const ring of f.geometry.coordinates) {
  for (let i = 0; i + 1 < ring.length; i++) {
    const a = ring[i].map(round), b = ring[i + 1].map(round), key = [a, b].map(String).sort().join('|');
    if (!edges.has(key)) edges.set(key, [...a, ...b]);
  }
}
// Join consecutive edges into polylines.
const bounds = [];
for (const e of edges.values()) {
  const last = bounds.at(-1);
  if (last && last.at(-2) === e[0] && last.at(-1) === e[1]) last.push(e[2], e[3]);
  else bounds.push([...e]);
}

// Milky Way isophotes (5 levels), thinned to points 0.6° apart; rings of
// less than four points are dropped.
const milkyWay = read('mw.json').map((f) => f.geometry.coordinates.flatMap((poly) => poly.map((ring) => {
  const out = [];
  let last = null;
  for (const [ra, dec] of ring) {
    if (last && Math.hypot(((ra - last[0] + 540) % 360 - 180) * Math.cos(dec * Math.PI / 180), dec - last[1]) < 0.6) continue;
    out.push(Math.round(ra * 10) / 10, Math.round(dec * 10) / 10); last = [ra, dec];
  }
  return out;
}).filter((r) => r.length >= 8)));

const license = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8');
const json = (x) => JSON.stringify(x);
fs.writeFileSync(new URL('../js/skydata.js', import.meta.url),
  '// Generated by tools/coelum.mjs. Stars: XHIP (Anderson & Francis, 2012),\n' +
  '// via d3-celestial; constellation figures, boundaries, label positions and\n' +
  '// Milky Way outlines: Olaf Frohn. https://github.com/ofrohn/d3-celestial —\n' +
  '// see SKY_DATA_LICENSE below. Double and variable flags: Hipparcos (ESA 1997).\n' +
  '// CHART_STARS: [HIP, RA (signed degrees, J2000), Dec, V magnitude, B−V,\n' +
  '//   flags (1 double, 2 variable; omitted when 0)].\n' +
  '// CONSTELLATIONS: [Latin name, RA, Dec, arrays of polylines (J2000)].\n' +
  '// BOUNDARIES: flat [RA, Dec, RA, Dec…] polylines (J2000).\n' +
  '// MILKY_WAY: five isophote levels, each a list of flat [RA, Dec…] rings.\n' +
  `export const SKY_DATA_LICENSE = ${json(license)};\n` +
  `export const CHART_STARS = [\n${stars.map(json).join(',\n')}\n];\n` +
  `export const CONSTELLATIONS = ${json(lines)};\n` +
  `export const BOUNDARIES = ${json(bounds)};\n` +
  `export const MILKY_WAY = ${json(milkyWay)};\n`);
const flagged = stars.filter((s) => s[5]);
console.log(`${stars.length} stars (${flagged.filter((s) => s[5] & 1).length} double, ${flagged.filter((s) => s[5] & 2).length} variable), ${bounds.length} boundary lines, Milky Way ${milkyWay.map((l) => l.reduce((n, r) => n + r.length / 2, 0)).join('/')} points`);
