// Writes js/minorplanets.js, the orbits of the brighter minor planets, the
// dwarf planets and some visited or famous ones:
//
//   node tools/minorplanets.mjs <directory>
//
// The list: the numbered minor planets that reach magnitude 10.5 at a
// perihelic opposition (H + 5 log q(q − 1)), from the JPL Small-Body
// Database, and those of EXTRA. For each, its osculating heliocentric
// elements (ecliptic and equinox of J2000) on the first of January of each
// year from 2016 to 2040, from JPL Horizons, kept in the directory (once),
// rounded to 0.1″ or better.
// The app takes the elements of the year nearest to the date: within half
// a year of them, a fixed orbit is good to some arcseconds (25″ at worst
// for Ceres and Vesta).

import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node tools/minorplanets.mjs <directory>");
fs.mkdirSync(dir, { recursive: true });

const FIRST = 2016, LAST = 2040;
// dwarf planets, and the minor planets visited by spacecraft or famous
const EXTRA = [134340, 136199, 136108, 136472, 225088, 50000, 90377, 90482, 433, 243, 951, 253, 21, 2867, 25143, 162173, 101955, 99942,
  65803, 3200, 4179, 486958, 52246, 152830, 3122, 1036, 4660, 5535, 9969];

async function cached(file, url) {
  const f = path.join(dir, file);
  if (fs.existsSync(f)) return fs.readFileSync(f, "utf8");
  for (let k = 0; k < 3; k++) {
    const r = await fetch(url);
    if (r.ok) {
      const t = await r.text();
      fs.writeFileSync(f, t);
      return t;
    }
    await new Promise((res) => setTimeout(res, 2000));
  }
  throw new Error(`cannot fetch ${url}`);
}

// the list, with H and G
const sbdb = "https://ssd-api.jpl.nasa.gov/sbdb_query.api?full-prec=1&fields=pdes,name,q,H,G&sb-kind=a&sb-ns=n&sb-cdata=";
const bright = JSON.parse(await cached("sbdb-bright.json", sbdb + encodeURIComponent(JSON.stringify({ AND: ["H|LT|11.5"] })))).data;
const extra = JSON.parse(await cached("sbdb-extra.json", sbdb + encodeURIComponent(JSON.stringify({ OR: EXTRA.map((n) => `pdes|EQ|${n}`) })))).data;
const peak = ([, , q, H]) => (Number(q) > 1.05 ? Number(H) + 5 * Math.log10(Number(q) * (Number(q) - 1)) : 99);
const list = new Map();
for (const r of [...bright.filter((r) => peak(r) < 10.5), ...extra]) list.set(Number(r[0]), r);

// the elements of each year: [epoch (JD), q, e, i, node, peri, tp]
async function elements(n) {
  const u = new URL("https://ssd.jpl.nasa.gov/api/horizons.api");
  const p = {
    format: "text", COMMAND: `'${n};'`, EPHEM_TYPE: "ELEMENTS", CENTER: "'500@10'", REF_PLANE: "ECLIPTIC", REF_SYSTEM: "J2000",
    START_TIME: `'${FIRST}-01-01'`, STOP_TIME: `'${LAST}-01-01'`, STEP_SIZE: "'1 y'", CSV_FORMAT: "YES", TIME_TYPE: "TDB", OUT_UNITS: "AU-D",
  };
  for (const [k, v] of Object.entries(p)) u.searchParams.set(k, v);
  const t = await cached(`horizons-${n}.txt`, u);
  const m = t.split("$$SOE")[1]?.split("$$EOE")[0];
  if (!m) throw new Error(`Horizons, ${n}: ${t.slice(0, 500)}`);
  // JDTDB, Calendar, EC, QR, IN, OM, W, Tp, …
  return m.trim().split("\n").map((l) => { const f = l.split(",").map((x) => x.trim()); return [+f[0], +f[3], +f[2], +f[4], +f[5], +f[6], +f[7]]; });
}

const rows = [];
let epochs = null;
for (const [n, [, name, , H, G]] of [...list].sort((a, b) => a[0] - b[0])) {
  const els = await elements(n);
  if (!epochs) epochs = els.map((e) => e[0]);
  if (els.length !== epochs.length || els.some((e, k) => e[0] !== epochs[k])) throw new Error(`epochs of ${n}`);
  const r = (x, d) => Number(x.toFixed(d));
  // q, e, i, node, peri, and the time of perihelion from the epoch (days)
  rows.push([n, name || "", Number(H), G === null || G === "" ? 0.15 : Number(G), els.map((e) => [r(e[1], 7), r(e[2], 7), r(e[3], 5), r(e[4], 5), r(e[5], 5), r(e[6] - e[0], 4)])]);
}

const out = `// Generated by tools/minorplanets.mjs: the brighter minor planets, the
// dwarf planets and some visited or famous ones, with their osculating
// heliocentric elements (ecliptic and equinox of J2000) from JPL Horizons
// on the first of January of each year, at the Julian days (TDB) EPOCHS.
//
// MINOR_PLANETS: [number, name, H, G, [[q (au), e, i, node, perihelion
// (degrees), time of perihelion − epoch (days)] for each epoch]].

const EPOCHS = ${JSON.stringify(epochs)};

const MINOR_PLANETS = [
${rows.map((r) => "  " + JSON.stringify(r)).join(",\n")},
];

export { EPOCHS, MINOR_PLANETS };
`;
fs.writeFileSync(new URL("../js/minorplanets.js", import.meta.url), out);
console.log(`${rows.length} minor planets, ${epochs.length} epochs, ${out.length} bytes`);
