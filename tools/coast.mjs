// Generate the shared globe coastlines from generalized Natural Earth 1:10m
// GeoJSON. Inputs: fine (250m), optional medium (2km), optional overview (20km).
// See data/coast-SOURCE.md for pinned source and preparation commands.
// node tools/coast.mjs fine.geojson medium.geojson overview.geojson
import fs from 'node:fs';
const SCALE = 100000;
const levels = process.argv.slice(2).map((file, index) => {
  const src = JSON.parse(fs.readFileSync(file, 'utf8')), lines = [];
  for (const feature of src.features) {
    const geometry = feature.geometry;
    if (!geometry) continue;
    for (const part of geometry.type === 'MultiLineString' ? geometry.coordinates : [geometry.coordinates]) {
      let px = 0, py = 0;
      const out = [];
      for (const [lon, lat] of part) {
        const x = Math.round(lon * SCALE), y = Math.round(lat * SCALE);
        if (out.length && x === px && y === py) continue;
        out.push(out.length ? x - px : x, out.length ? y - py : y); px = x; py = y;
      }
      if (out.length >= 4) lines.push(out);
    }
  }
  return { tolerance: [250, 2000, 20000][index], lines };
});
if (!levels.length) throw new Error('Supply at least the fine coastline GeoJSON');
const literal = lines => `[\n${lines.map(line => JSON.stringify(line)).join(',\n')}\n]`;
const source = `// Natural Earth 1:10m coastlines (public domain), generalized from geographic\n// vectors. Generated by tools/coast.mjs; provenance: data/coast-SOURCE.md.\n// Longitude/latitude integer deltas at COAST_SCALE units per degree.\nexport const COAST_SCALE = ${SCALE};\nexport const COAST = ${literal(levels[0].lines)};\nexport const COAST_LEVELS = [\n${levels.slice(1).reverse().map(level => `{ tolerance: ${level.tolerance}, lines: ${literal(level.lines)} },`).join('\n')}\n{ tolerance: 250, lines: COAST }\n];\n`;
fs.writeFileSync(new URL('../js/coast.js', import.meta.url), source);
for (const level of levels) console.log(`${level.tolerance}m: ${level.lines.length} lines, ${level.lines.reduce((n, line) => n + line.length / 2, 0)} vertices`);
console.log(`${source.length.toLocaleString()} bytes`);
