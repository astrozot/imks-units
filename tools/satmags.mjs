// Writes js/satmags.js, the standard magnitudes of the satellites of
// CelesTrak's groups that the apps offer (js/satellites.js):
//
//   node tools/satmags.mjs <quicksat.mag>
//
// quicksat.mag is Mike McCants' list of intrinsic magnitudes, in qsmag.zip
// from https://www.mmccants.org/programs/: fixed columns, the NORAD number
// in 1–5 and the magnitude in 34–38, at 1000 km and half lit (phase angle
// 90°). The groups come from CelesTrak now; their members without a
// magnitude there get the app's default for the group, or one of EXTRA.
// Run it again from time to time, as the groups change.

import fs from "node:fs";

const file = process.argv[2];
if (!file) throw new Error("usage: node tools/satmags.mjs <quicksat.mag>");
const GROUPS = ["stations", "visual", "science", "amateur", "weather"];
// estimates where the list has none: the Chinese station whole (its core,
// Tianhe, with Wentian and Mengtian), brighter than its modules alone
const EXTRA = { 48274: -1.0 };

const mags = new Map();
for (const line of fs.readFileSync(file, "latin1").split("\n")) {
  const n = Number(line.slice(0, 5)), m = Number.parseFloat(line.slice(33, 38));
  if (n && Number.isFinite(m)) mags.set(n, m);
}
const wanted = new Map();
for (const g of GROUPS) {
  const res = await fetch(`https://celestrak.org/NORAD/elements/gp.php?GROUP=${g}&FORMAT=json`);
  if (!res.ok) throw new Error(`CelesTrak ${g}: HTTP ${res.status}`);
  for (const o of await res.json()) {
    const m = EXTRA[o.NORAD_CAT_ID] ?? mags.get(o.NORAD_CAT_ID);
    if (m !== undefined) wanted.set(o.NORAD_CAT_ID, m);
  }
}
const sorted = [...wanted].sort((a, b) => a[0] - b[0]);
fs.writeFileSync(new URL("../js/satmags.js", import.meta.url), `// Generated by tools/satmags.mjs: the standard magnitudes of satellites
// (at 1000 km, half lit) of CelesTrak's groups offered by the apps, from
// Mike McCants' quicksat.mag, by NORAD number; a few estimated (EXTRA of
// the tool).

const SAT_MAGS = {${sorted.map(([n, m]) => `${n}:${m}`).join(",")}};

export { SAT_MAGS };
`);
console.log(`${sorted.length} magnitudes written`);
