import assert from 'node:assert/strict';
import fs from 'node:fs';
import { DEEP as builtin } from '../js/catalog.js';
import { findObject as lookup } from '../js/lookup.js';
import { skyFrame, searchSky, objectDetails, skyChart, createSkyAnimator } from '../js/coelum.js';
import * as catalog from '../js/deepcatalog.js';
const source = fs.readFileSync(new URL('../data/openngc.json', import.meta.url), 'utf8');
const stored = new Map();
globalThis.caches = { open: async () => ({ match: async (k) => stored.get(k)?.clone(), put: async (k, res) => stored.set(k, res), delete: async (k) => stored.delete(k) }), delete: async () => stored.clear() };
let response = source;
globalThis.fetch = async () => new Response(response);
await catalog.loadOpenNGC();
assert.equal(catalog.DEEP.length, 232);
assert.throws(() => lookup({}, 'NGC 7814'));
await catalog.downloadOpenNGC();
assert.equal(catalog.openNGCCount(), 13366);
for (const row of builtin) {
  const merged = catalog.DEEP.find((r) => r[0][0] === row[0][0]);
  assert.deepEqual(merged.slice(1, 7), row.slice(1, 7));
  assert.ok(row[0].every((n) => merged[0].includes(n)));
}
const keys = catalog.DEEP.map((r) => r[0][0]);
assert.equal(new Set(keys).size, keys.length);
assert.equal(lookup({}, 'ngc 07814').kind, 'galaxy');
const frame = skyFrame(Date.UTC(2026, 10, 18) / 1000, [45, 9, 0]);
assert.equal(frame.deep.length, 13366);
assert.equal(searchSky(frame, 'NGC 7814')[0].name, 'NGC 7814');
assert.equal(searchSky(frame, 'NGC 07814')[0].name, 'NGC 7814');
const blue = frame.deep.find((o) => o.magBand === 'B');
assert.match(objectDetails(blue, frame), /Blue magnitude \(B\)/);
assert.ok(skyChart(frame).objects.filter((o) => keys.includes(o.name)).length < 300, 'Wide view avoids flooding the chart with faint symbols');
assert.ok(!catalog.showDeepObject({ name: 'NGC 2', mag: 15 }, 1));
assert.ok(catalog.showDeepObject({ name: 'NGC 2', mag: 15 }, 16));
assert.ok(catalog.showDeepObject({ name: 'NGC 2', mag: 15 }, 1, 'NGC 2'));
const start = performance.now();
createSkyAnimator(frame.t, frame.place)(frame.t + 1);
console.log(`Expanded frame and playback build: ${(performance.now() - start).toFixed(0)} ms`);
const restored = await import('../js/deepcatalog.js?restore');
await restored.loadOpenNGC();
assert.equal(restored.openNGCCount(), 13366, 'Saved download restores without fetch');
response = source.slice(0, -50);
await assert.rejects(catalog.downloadOpenNGC());
assert.equal(catalog.openNGCCount(), 13366, 'Truncation keeps the working catalog');
await catalog.removeOpenNGC();
assert.equal(catalog.DEEP, builtin);
assert.throws(() => lookup({}, 'NGC 7814'), 'Removal invalidates calculator lookup');
assert.equal(stored.size, 0);
console.log('OpenNGC import, aliases, search, photometry, rendering, offline restore, failure and removal passed');
